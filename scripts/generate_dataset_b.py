import cv2
import os
import random
import numpy as np
from tqdm import tqdm



FLAG_PATH = "/content/drive/MyDrive/Flag design background removed.png"
BACKGROUND_DIR = "/content/drive/MyDrive/images"

OUTPUT_DIR = "dataset_B"

NUM_IMAGES = 1000


for split in ["train", "val", "test"]:

    os.makedirs(
        os.path.join(
            OUTPUT_DIR,
            "images",
            split
        ),
        exist_ok=True
    )

    os.makedirs(
        os.path.join(
            OUTPUT_DIR,
            "labels",
            split
        ),
        exist_ok=True
    )



flag = cv2.imread(
    FLAG_PATH,
    cv2.IMREAD_UNCHANGED
)

if flag is None:
    raise ValueError("Could not load flag image")

if flag.shape[2] != 4:
    raise ValueError(
        "Flag PNG must have alpha channel"
    )



backgrounds = [
    os.path.join(BACKGROUND_DIR, f)
    for f in os.listdir(BACKGROUND_DIR)
]

if len(backgrounds) == 0:
    raise ValueError(
        "No background images found"
    )



indices = list(range(NUM_IMAGES))

random.shuffle(indices)

train_end = int(0.7 * NUM_IMAGES)
val_end = int(0.9 * NUM_IMAGES)

split_map = {}

for idx in indices[:train_end]:
    split_map[idx] = "train"

for idx in indices[train_end:val_end]:
    split_map[idx] = "val"

for idx in indices[val_end:]:
    split_map[idx] = "test"



for i in tqdm(range(NUM_IMAGES)):

    split = split_map[i]


    # RANDOM BACKGROUND


    bg_path = random.choice(backgrounds)

    bg = cv2.imread(bg_path)

    if bg is None:
        continue

    bg_h, bg_w = bg.shape[:2]


    # RANDOM SCALE

    scale = np.random.beta(2, 5)
    scale = 0.05 + scale * 0.45

    aspect_ratio = flag.shape[0] / flag.shape[1]

    new_w = int(bg_w * scale)
    new_h = int(new_w * aspect_ratio)

    new_w = max(new_w, 32)
    new_h = max(new_h, 32)

    if new_w >= bg_w:
        continue

    if new_h >= bg_h:
        continue

    resized_flag = cv2.resize(
        flag,
        (new_w, new_h),
        interpolation=cv2.INTER_AREA
    )


    # PERSPECTIVE WARP


    h, w = resized_flag.shape[:2]

    src_pts = np.float32([
        [0, 0],
        [w, 0],
        [w, h],
        [0, h]
    ])

    max_shift = int(
        min(w, h) * 0.25
    )

    dst_pts = np.float32([
        [
            random.randint(0, max_shift),
            random.randint(0, max_shift)
        ],
        [
            w - random.randint(0, max_shift),
            random.randint(0, max_shift)
        ],
        [
            w - random.randint(0, max_shift),
            h - random.randint(0, max_shift)
        ],
        [
            random.randint(0, max_shift),
            h - random.randint(0, max_shift)
        ]
    ])

    M = cv2.getPerspectiveTransform(
        src_pts,
        dst_pts
    )

    warped_flag = cv2.warpPerspective(
        resized_flag,
        M,
        (w, h),
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=(0, 0, 0, 0)
    )


    # TIGHT MASK AFTER WARP


    alpha_mask = warped_flag[:, :, 3]

    ys, xs = np.where(
        alpha_mask > 10
    )

    if len(xs) == 0:
        continue

    xmin = xs.min()
    xmax = xs.max()

    ymin = ys.min()
    ymax = ys.max()

    tight_flag = warped_flag[
        ymin:ymax+1,
        xmin:xmax+1
    ]

    flag_h, flag_w = tight_flag.shape[:2]

    if flag_h < 5 or flag_w < 5:
        continue


    # RANDOM POSITION


    if flag_w >= bg_w:
        continue

    if flag_h >= bg_h:
        continue

    x = random.randint(
        0,
        bg_w - flag_w
    )

    y = random.randint(
        0,
        bg_h - flag_h
    )



    rgb = tight_flag[:, :, :3]

    alpha = (
        tight_flag[:, :, 3]
        / 255.0
    )

    for c in range(3):

        bg[
            y:y+flag_h,
            x:x+flag_w,
            c
        ] = (

            alpha * rgb[:, :, c]

            +

            (1 - alpha)

            * bg[
                y:y+flag_h,
                x:x+flag_w,
                c
            ]

        )


    # ANNOTATIONS

    box_xmin = x
    box_xmax = x + flag_w

    box_ymin = y
    box_ymax = y + flag_h

    x_center = (
        (box_xmin + box_xmax)
        / 2
    ) / bg_w

    y_center = (
        (box_ymin + box_ymax)
        / 2
    ) / bg_h

    width = (
        box_xmax - box_xmin
    ) / bg_w

    height = (
        box_ymax - box_ymin
    ) / bg_h


    img_name = f"img_{i}.jpg"

    cv2.imwrite(
        os.path.join(
            OUTPUT_DIR,
            "images",
            split,
            img_name
        ),
        bg
    )



    label_name = f"img_{i}.txt"

    with open(
        os.path.join(
            OUTPUT_DIR,
            "labels",
            split,
            label_name
        ),
        "w"
    ) as f:

        f.write(
            f"0 {x_center:.6f} {y_center:.6f} {width:.6f} {height:.6f}"
        )

print("Dataset B created successfully!")