import cv2
import os
import random
import numpy as np
from tqdm import tqdm


BACKGROUND_DIR = "/content/drive/MyDrive/images"
OUTPUT_DIR = "dataset_E"


FLAG_CONFIGS = [
    {"path": "/content/drive/MyDrive/triangle_flag_background_removed.png", "num_images": 250},
    {"path": "/content/drive/MyDrive/Square_Flag_background_removed.png", "num_images": 250}
]


os.makedirs(os.path.join(OUTPUT_DIR, "images"), exist_ok=True)
os.makedirs(os.path.join(OUTPUT_DIR, "labels"), exist_ok=True)


def generate_synthetic_data(flag_path, num_to_generate, start_index, backgrounds):
    """Loads a specific flag asset and blends it into random backgrounds."""

    flag = cv2.imread(flag_path, cv2.IMREAD_UNCHANGED)
    if flag is None:
        print(f"Skipping: Could not load flag image at {flag_path}")
        return start_index

    if flag.shape[2] != 4:
        print(f"Skipping: Flag PNG at {flag_path} must have an alpha channel")
        return start_index

    print(f"\nGenerating {num_to_generate} images for: {os.path.basename(flag_path)}")

    generated_count = 0
    current_idx = start_index

    with tqdm(total=num_to_generate) as pbar:
        while generated_count < num_to_generate:

            # Pick a random background
            bg_path = random.choice(backgrounds)
            bg = cv2.imread(bg_path)
            if bg is None:
                continue

            bg_h, bg_w = bg.shape[:2]


            # RANDOM SCALE

            scale = np.random.beta(2, 5)
            scale = 0.05 + scale * 0.45


            aspect_ratio = flag.shape[0] / flag.shape[1]

            new_w = int(bg_w * scale)
            new_h = int(new_w * aspect_ratio)

            new_w = max(new_w, 32)
            new_h = max(new_h, 32)

            if new_w >= bg_w or new_h >= bg_h:
                continue

            resized_flag = cv2.resize(flag, (new_w, new_h), interpolation=cv2.INTER_AREA)


            # PERSPECTIVE WARP

            h, w = resized_flag.shape[:2]
            src_pts = np.float32([[0, 0], [w, 0], [w, h], [0, h]])
            max_shift = int(min(w, h) * 0.25)

            dst_pts = np.float32([
                [random.randint(0, max_shift), random.randint(0, max_shift)],
                [w - random.randint(0, max_shift), random.randint(0, max_shift)],
                [w - random.randint(0, max_shift), h - random.randint(0, max_shift)],
                [random.randint(0, max_shift), h - random.randint(0, max_shift)]
            ])

            M = cv2.getPerspectiveTransform(src_pts, dst_pts)
            warped_flag = cv2.warpPerspective(
                resized_flag, M, (w, h),
                borderMode=cv2.BORDER_CONSTANT, borderValue=(0, 0, 0, 0)
            )


            # TIGHT MASK AFTER WARP

            alpha_mask = warped_flag[:, :, 3]
            ys, xs = np.where(alpha_mask > 10)

            if len(xs) == 0:
                continue

            xmin, xmax = xs.min(), xs.max()
            ymin, ymax = ys.min(), ys.max()

            tight_flag = warped_flag[ymin:ymax+1, xmin:xmax+1]
            flag_h, flag_w = tight_flag.shape[:2]

            if flag_h < 5 or flag_w < 5:
                continue

            # RANDOM POSITION
            if flag_w >= bg_w or flag_h >= bg_h:
                continue

            x = random.randint(0, bg_w - flag_w)
            y = random.randint(0, bg_h - flag_h)


            # PHOTOMETRIC AUGMENTATION

            rgb = tight_flag[:, :, :3].astype(np.float32)

            # Brightness & Contrast
            brightness = random.uniform(0.6, 1.4)
            rgb *= brightness
            contrast = random.uniform(0.6, 1.4)
            rgb = (rgb - 127.5) * contrast + 127.5

            # Saturation
            hsv = cv2.cvtColor(np.clip(rgb, 0, 255).astype(np.uint8), cv2.COLOR_BGR2HSV)
            sat_scale = random.uniform(0.7, 1.3)
            hsv[:, :, 1] = np.clip(hsv[:, :, 1] * sat_scale, 0, 255)
            rgb = cv2.cvtColor(hsv, cv2.COLOR_HSV2BGR).astype(np.float32)

            # Temperature Shift
            temp_shift = random.randint(-25, 25)
            rgb[:, :, 2] = np.clip(rgb[:, :, 2] + temp_shift, 0, 255)
            rgb[:, :, 0] = np.clip(rgb[:, :, 0] - temp_shift, 0, 255)

            # Noise
            noise_std = random.uniform(0, 8)
            rgb += np.random.normal(0, noise_std, rgb.shape)
            rgb = np.clip(rgb, 0, 255).astype(np.uint8)

            alpha = tight_flag[:, :, 3].astype(np.float32) / 255.0


            roi = bg[y:y+flag_h, x:x+flag_w]
            for c in range(3):
                roi[:, :, c] = alpha * rgb[:, :, c] + (1.0 - alpha) * roi[:, :, c]
            bg[y:y+flag_h, x:x+flag_w] = roi



            # Shadow Augmentation
            if random.random() < 0.7:
                shadow_mask = np.zeros((bg_h, bg_w), dtype=np.uint8)
                x1, y1 = random.randint(0, bg_w), random.randint(0, bg_h)
                x2, y2 = random.randint(0, bg_w), random.randint(0, bg_h)
                thickness = random.randint(int(min(bg_h, bg_w) * 0.1), int(min(bg_h, bg_w) * 0.3))
                cv2.line(shadow_mask, (x1, y1), (x2, y2), 255, thickness)
                shadow_mask = cv2.GaussianBlur(shadow_mask, (101, 101), 0).astype(np.float32) / 255.0
                bg = bg.astype(np.float32)
                for c in range(3):
                    bg[:, :, c] *= (1.0 - shadow_mask * random.uniform(0.4, 0.8))
                bg = np.clip(bg, 0, 255).astype(np.uint8)

            # Occlusion Augmentation
            if random.random() < 0.6:
                for _ in range(random.randint(1, 3)):
                    occ_type = random.choice(["rectangle", "circle"])
                    occ_w = random.randint(int(flag_w * 0.15), int(flag_w * 0.4))
                    occ_h = random.randint(int(flag_h * 0.15), int(flag_h * 0.4))
                    occ_x = random.randint(x, x + flag_w - 1)
                    occ_y = random.randint(y, y + flag_h - 1)
                    color = (random.randint(0, 255), random.randint(0, 255), random.randint(0, 255))

                    if occ_type == "rectangle":
                        cv2.rectangle(bg, (occ_x, occ_y), (min(bg_w - 1, occ_x + occ_w), min(bg_h - 1, occ_y + occ_h)), color, -1)
                    else:
                        cv2.circle(bg, (occ_x, occ_y), occ_w // 2, color, -1)

            # Blurs
            if random.random() < 0.5:
                k = random.choice([3, 5, 7])
                bg = cv2.GaussianBlur(bg, (k, k), 0)

            if random.random() < 0.4:
                k_size = random.choice([7, 9, 11, 15])
                kernel = np.zeros((k_size, k_size))
                if random.choice(["horizontal", "vertical"]) == "horizontal":
                    kernel[k_size // 2, :] = np.ones(k_size)
                else:
                    kernel[:, k_size // 2] = np.ones(k_size)
                bg = cv2.filter2D(bg, -1, kernel / k_size)


            # ANNOTATIONS

            x_center = ((x + (x + flag_w)) / 2.0) / bg_w
            y_center = ((y + (y + flag_h)) / 2.0) / bg_h
            width = flag_w / bg_w
            height = flag_h / bg_h


            img_name = f"img_{current_idx}.jpg"
            label_name = f"img_{current_idx}.txt"

            cv2.imwrite(os.path.join(OUTPUT_DIR, "images", img_name), bg)
            with open(os.path.join(OUTPUT_DIR, "labels", label_name), "w") as f:
                f.write(f"0 {x_center:.6f} {y_center:.6f} {width:.6f} {height:.6f}")

            generated_count += 1
            current_idx += 1
            pbar.update(1)

    return current_idx


if __name__ == "__main__":
    if not os.path.exists(BACKGROUND_DIR):
        raise ValueError(f"Background directory missing: {BACKGROUND_DIR}")

    backgrounds = [
        os.path.join(BACKGROUND_DIR, f)
        for f in os.listdir(BACKGROUND_DIR)
        if f.lower().endswith(('.png', '.jpg', '.jpeg', '.webp'))
    ]

    if len(backgrounds) == 0:
        raise ValueError("No background images found in background directory")


    global_img_idx = 0

    for config in FLAG_CONFIGS:
        global_img_idx = generate_synthetic_data(
            flag_path=config["path"],
            num_to_generate=config["num_images"],
            start_index=global_img_idx,
            backgrounds=backgrounds
        )

    print("\nDataset_E generated successfully!")