import cv2
import os
import random
import numpy as np
from tqdm import tqdm


# PATHS


FLAG_PATH = "/content/drive/MyDrive/Flag design background removed.png"
BACKGROUND_DIR = "/content/drive/MyDrive/images"

OUTPUT_DIR = "dataset_A"

NUM_IMAGES = 1000


# CREATE TRAIN/VAL/TEST

for split in ["train", "val", "test"]:

    os.makedirs(
        os.path.join(
            OUTPUT_DIR,
            "images",
            split
        ),
        exist_ok=True
    )

    os.makedirs(
        os.path.join(
            OUTPUT_DIR,
            "labels",
            split
        ),
        exist_ok=True
    )


# LOAD FLAG


flag = cv2.imread(
    FLAG_PATH,
    cv2.IMREAD_UNCHANGED
)

if flag is None:
    raise ValueError("Could not load flag image")

if flag.shape[2] != 4:
    raise ValueError(
        "Flag PNG must have an alpha channel"
    )


# LOAD BACKGROUNDS


backgrounds = [
    os.path.join(BACKGROUND_DIR, f)
    for f in os.listdir(BACKGROUND_DIR)
]

if len(backgrounds) == 0:
    raise ValueError(
        "No background images found"
    )


# CREATE SPLIT MAP


indices = list(range(NUM_IMAGES))

random.shuffle(indices)

train_end = int(0.7 * NUM_IMAGES)
val_end = int(0.9 * NUM_IMAGES)

split_map = {}

for idx in indices[:train_end]:
    split_map[idx] = "train"

for idx in indices[train_end:val_end]:
    split_map[idx] = "val"

for idx in indices[val_end:]:
    split_map[idx] = "test"


# GENERATION LOOP


for i in tqdm(range(NUM_IMAGES)):

    split = split_map[i]


    # RANDOM BACKGROUND


    bg_path = random.choice(backgrounds)

    bg = cv2.imread(bg_path)

    if bg is None:
        continue

    bg_h, bg_w = bg.shape[:2]


    # REALISTIC SCALE


    scale = np.random.beta(2, 5)
    scale = 0.05 + scale * 0.45

    aspect_ratio = flag.shape[0] / flag.shape[1]

    new_w = int(bg_w * scale)
    new_h = int(new_w * aspect_ratio)

    new_w = max(new_w, 32)
    new_h = max(new_h, 32)

    if new_w >= bg_w:
        continue

    if new_h >= bg_h:
        continue

    resized_flag = cv2.resize(
        flag,
        (new_w, new_h),
        interpolation=cv2.INTER_AREA
    )


    # RANDOM POSITION


    x = random.randint(
        0,
        bg_w - new_w
    )

    y = random.randint(
        0,
        bg_h - new_h
    )



    rgb = resized_flag[:, :, :3]

    alpha = resized_flag[:, :, 3] / 255.0

    for c in range(3):

        bg[
            y:y+new_h,
            x:x+new_w,
            c
        ] = (
            alpha * rgb[:, :, c]
            +
            (1 - alpha)
            * bg[
                y:y+new_h,
                x:x+new_w,
                c
            ]
        )


    # TIGHT BOUNDING BOX


    alpha_mask = resized_flag[:, :, 3]

    ys, xs = np.where(alpha_mask > 10)

    if len(xs) == 0:
        continue

    xmin = xs.min()
    xmax = xs.max()

    ymin = ys.min()
    ymax = ys.max()

    box_xmin = x + xmin
    box_xmax = x + xmax

    box_ymin = y + ymin
    box_ymax = y + ymax


    # ANNOTATION


    x_center = (
        (box_xmin + box_xmax) / 2
    ) / bg_w

    y_center = (
        (box_ymin + box_ymax) / 2
    ) / bg_h

    width = (
        box_xmax - box_xmin
    ) / bg_w

    height = (
        box_ymax - box_ymin
    ) / bg_h


    # SAVE IMAGE


    img_name = f"img_{i}.jpg"

    cv2.imwrite(
        os.path.join(
            OUTPUT_DIR,
            "images",
            split,
            img_name
        ),
        bg
    )


    # SAVE LABEL


    label_name = f"img_{i}.txt"

    with open(
        os.path.join(
            OUTPUT_DIR,
            "labels",
            split,
            label_name
        ),
        "w"
    ) as f:

        f.write(
            f"0 {x_center:.6f} {y_center:.6f} {width:.6f} {height:.6f}"
        )

print("Done!")