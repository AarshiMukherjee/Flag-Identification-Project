import cv2
import os
import random
import numpy as np
from tqdm import tqdm



FLAG_PATH = "/content/drive/MyDrive/Flag design background removed.png"
BACKGROUND_DIR = "/content/drive/MyDrive/images"

OUTPUT_DIR = "dataset_D"

NUM_IMAGES = 1000



for split in ["train", "val", "test"]:

    os.makedirs(
        os.path.join(
            OUTPUT_DIR,
            "images",
            split
        ),
        exist_ok=True
    )

    os.makedirs(
        os.path.join(
            OUTPUT_DIR,
            "labels",
            split
        ),
        exist_ok=True
    )



flag = cv2.imread(
    FLAG_PATH,
    cv2.IMREAD_UNCHANGED
)

if flag is None:
    raise ValueError("Could not load flag image")

if flag.shape[2] != 4:
    raise ValueError(
        "Flag PNG must have alpha channel"
    )



backgrounds = [
    os.path.join(BACKGROUND_DIR, f)
    for f in os.listdir(BACKGROUND_DIR)
]

if len(backgrounds) == 0:
    raise ValueError(
        "No background images found"
    )


# TRAIN / VAL / TEST SPLIT


indices = list(range(NUM_IMAGES))

random.shuffle(indices)

train_end = int(0.7 * NUM_IMAGES)
val_end = int(0.9 * NUM_IMAGES)

split_map = {}

for idx in indices[:train_end]:
    split_map[idx] = "train"

for idx in indices[train_end:val_end]:
    split_map[idx] = "val"

for idx in indices[val_end:]:
    split_map[idx] = "test"


# GENERATION LOOP


for i in tqdm(range(NUM_IMAGES)):

    split = split_map[i]


    # RANDOM BACKGROUND

    bg_path = random.choice(backgrounds)

    bg = cv2.imread(bg_path)

    if bg is None:
        continue

    bg_h, bg_w = bg.shape[:2]

    # RANDOM SCALE


    scale = np.random.beta(2, 5)
    scale = 0.05 + scale * 0.45

    aspect_ratio = flag.shape[0] / flag.shape[1]

    new_w = int(bg_w * scale)
    new_h = int(new_w * aspect_ratio)

    new_w = max(new_w, 32)
    new_h = max(new_h, 32)

    if new_w >= bg_w:
        continue

    if new_h >= bg_h:
        continue

    resized_flag = cv2.resize(
        flag,
        (new_w, new_h),
        interpolation=cv2.INTER_AREA
    )


    # PERSPECTIVE WARP


    h, w = resized_flag.shape[:2]

    src_pts = np.float32([
        [0, 0],
        [w, 0],
        [w, h],
        [0, h]
    ])

    max_shift = int(
        min(w, h) * 0.25
    )

    dst_pts = np.float32([
        [
            random.randint(0, max_shift),
            random.randint(0, max_shift)
        ],
        [
            w - random.randint(0, max_shift),
            random.randint(0, max_shift)
        ],
        [
            w - random.randint(0, max_shift),
            h - random.randint(0, max_shift)
        ],
        [
            random.randint(0, max_shift),
            h - random.randint(0, max_shift)
        ]
    ])

    M = cv2.getPerspectiveTransform(
        src_pts,
        dst_pts
    )

    warped_flag = cv2.warpPerspective(
        resized_flag,
        M,
        (w, h),
        borderMode=cv2.BORDER_CONSTANT,
        borderValue=(0, 0, 0, 0)
    )


    # TIGHT MASK AFTER WARP


    alpha_mask = warped_flag[:, :, 3]

    ys, xs = np.where(
        alpha_mask > 10
    )

    if len(xs) == 0:
        continue

    xmin = xs.min()
    xmax = xs.max()

    ymin = ys.min()
    ymax = ys.max()

    tight_flag = warped_flag[
        ymin:ymax+1,
        xmin:xmax+1
    ]

    flag_h, flag_w = tight_flag.shape[:2]

    if flag_h < 5 or flag_w < 5:
        continue


    # RANDOM POSITION


    if flag_w >= bg_w:
        continue

    if flag_h >= bg_h:
        continue

    x = random.randint(
        0,
        bg_w - flag_w
    )

    y = random.randint(
        0,
        bg_h - flag_h
    )



    rgb = tight_flag[:, :, :3].astype(np.float32)

    # Brightness

    brightness = random.uniform(0.6, 1.4)
    rgb *= brightness

    # Contrast

    contrast = random.uniform(0.6, 1.4)
    rgb = (rgb - 127.5) * contrast + 127.5

    # Saturation

    hsv = cv2.cvtColor(
        np.clip(rgb, 0, 255).astype(np.uint8),
        cv2.COLOR_BGR2HSV
    )

    sat_scale = random.uniform(0.7, 1.3)

    hsv[:, :, 1] = np.clip(
        hsv[:, :, 1] * sat_scale,
        0,
        255
    )

    rgb = cv2.cvtColor(
        hsv,
        cv2.COLOR_HSV2BGR
    ).astype(np.float32)

    # Warm / Cool color temperature

    temp_shift = random.randint(-25, 25)

    rgb[:, :, 2] = np.clip(
        rgb[:, :, 2] + temp_shift,
        0,
        255
    )

    rgb[:, :, 0] = np.clip(
        rgb[:, :, 0] - temp_shift,
        0,
        255
    )

    # Gaussian Noise

    noise_std = random.uniform(0, 8)

    noise = np.random.normal(
        0,
        noise_std,
        rgb.shape
    )

    rgb += noise

    rgb = np.clip(
        rgb,
        0,
        255
    ).astype(np.uint8)

    alpha = (
        tight_flag[:, :, 3].astype(np.float32)
        / 255.0
    )



    roi = bg[
        y:y+flag_h,
        x:x+flag_w
    ]

    for c in range(3):
        roi[:, :, c] = (
            alpha * rgb[:, :, c]
            + (1.0 - alpha) * roi[:, :, c]
        )

    bg[
        y:y+flag_h,
        x:x+flag_w
    ] = roi

    # DATASET D AUGMENTATIONS
    # Blur + Shadows + Occlusions


    # RANDOM SHADOW


    if random.random() < 0.7:

        shadow_mask = np.zeros(
            (bg_h, bg_w),
            dtype=np.uint8
        )

        x1 = random.randint(0, bg_w)
        y1 = random.randint(0, bg_h)

        x2 = random.randint(0, bg_w)
        y2 = random.randint(0, bg_h)

        thickness = random.randint(
            int(min(bg_h, bg_w)*0.1),
            int(min(bg_h, bg_w)*0.3)
        )

        cv2.line(
            shadow_mask,
            (x1, y1),
            (x2, y2),
            255,
            thickness
        )

        shadow_mask = cv2.GaussianBlur(
            shadow_mask,
            (101,101),
            0
        )

        darkness = random.uniform(
            0.4,
            0.8
        )

        shadow_mask = (
            shadow_mask.astype(np.float32)
            / 255.0
        )

        bg = bg.astype(np.float32)

        for c in range(3):
            bg[:,:,c] *= (
                1 - shadow_mask * darkness
            )

        bg = np.clip(
            bg,
            0,
            255
        ).astype(np.uint8)


    # RANDOM OCCLUSION


    if random.random() < 0.6:

        num_occ = random.randint(1, 3)

        for _ in range(num_occ):

            occ_type = random.choice([
                "rectangle",
                "circle"
            ])

            occ_w = random.randint(
                int(flag_w*0.15),
                int(flag_w*0.4)
            )

            occ_h = random.randint(
                int(flag_h*0.15),
                int(flag_h*0.4)
            )

            occ_x = random.randint(
                x,
                x + flag_w - 1
            )

            occ_y = random.randint(
                y,
                y + flag_h - 1
            )

            color = (
                random.randint(0,255),
                random.randint(0,255),
                random.randint(0,255)
            )

            if occ_type == "rectangle":

                cv2.rectangle(
                    bg,
                    (occ_x, occ_y),
                    (
                        min(bg_w-1, occ_x+occ_w),
                        min(bg_h-1, occ_y+occ_h)
                    ),
                    color,
                    -1
                )

            else:

                cv2.circle(
                    bg,
                    (occ_x, occ_y),
                    occ_w//2,
                    color,
                    -1
                )


    # GAUSSIAN BLUR


    if random.random() < 0.5:

        k = random.choice([
            3,
            5,
            7
        ])

        bg = cv2.GaussianBlur(
            bg,
            (k,k),
            0
        )


    # MOTION BLUR


    if random.random() < 0.4:

        kernel_size = random.choice([
            7,
            9,
            11,
            15
        ])

        kernel = np.zeros(
            (kernel_size, kernel_size)
        )

        direction = random.choice([
            "horizontal",
            "vertical"
        ])

        if direction == "horizontal":

            kernel[
                kernel_size//2,
                :
            ] = np.ones(kernel_size)

        else:

            kernel[
                :,
                kernel_size//2
            ] = np.ones(kernel_size)

        kernel = kernel / kernel_size

        bg = cv2.filter2D(
            bg,
            -1,
            kernel
        )


    # YOLO BOX


    box_xmin = x
    box_xmax = x + flag_w

    box_ymin = y
    box_ymax = y + flag_h

    x_center = (
        (box_xmin + box_xmax) / 2
    ) / bg_w

    y_center = (
        (box_ymin + box_ymax) / 2
    ) / bg_h

    width = (
        box_xmax - box_xmin
    ) / bg_w

    height = (
        box_ymax - box_ymin
    ) / bg_h


    # SAVE IMAGE


    img_name = f"img_{i}.jpg"

    cv2.imwrite(
        os.path.join(
            OUTPUT_DIR,
            "images",
            split,
            img_name
        ),
        bg
    )


    # SAVE LABEL


    label_name = f"img_{i}.txt"

    with open(
        os.path.join(
            OUTPUT_DIR,
            "labels",
            split,
            label_name
        ),
        "w"
    ) as f:

        f.write(
            f"0 {x_center:.6f} {y_center:.6f} {width:.6f} {height:.6f}"
        )

print("Dataset D created successfully!")